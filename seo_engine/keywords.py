def _uniquify(out: dict) -> None:
    """Listing titles must stay distinct — unique titles are a hard CRO/SEO
    requirement and generic names ("Browns", "Cleveland") would collide."""
    seen = {}
    for slug in sorted(out):
        e = out[slug]
        title = e["listing_title"]
        if title not in seen:
            seen[title] = slug
            continue
        base, _, g = title.rpartition(" ")
        for v in _GARMENT_VARIANTS.get(g, []):
            cand = f"{base} {v}"
            if cand not in seen:
                seen[cand] = slug
                e["listing_title"] = cand
                break
        else:
            cand = f"{title} Design"
            n = 2
            while cand in seen:
                cand = f"{title} Design {n}"
                n += 1
            seen[cand] = slug
            e["listing_title"] = cand


def build_map(model=None) -> dict:
    model = model or build.build_model()
    out = {}
    for items in model.values():
        if not isinstance(items, list):
            continue
        for it in items:
            if not isinstance(it, dict) or "slug" not in it:
                continue
            out[it["slug"]] = build_entry(it)
    _uniquify(out)
    return out


