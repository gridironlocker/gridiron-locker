    if (not derived or len(derived.split()) > 6 or derived.isdigit()
            or derived in GENERIC_DERIVED):
        derived = ""
    if derived and (not slogan or len(derived.split()) > len(slogan.split())):
        slogan = derived
    if slogan.isdigit() and len(slogan) != 4:  # bare years only
        slogan = ""
    slogan = slogan.strip()

    # slogan -> keyword: append team only when the phrase lacks it
    slogan_kw = ""
