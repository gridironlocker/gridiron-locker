# ── helpers ─────────────────────────────────────────────────────────────────
def _fold(s: str) -> str:
    return unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode().lower()


def _norm_phrase(art: str) -> str:
    """Lowercased, punctuation-flattened phrase (word order kept)."""
    return " ".join(re.sub(r"[^a-z0-9 ]", " ", _fold(art)).split())


def team_of(name: str):
    f = _fold(name)
    for full, t in TEAM.items():
        if _fold(full) in f:
            return t["core"], t
    for full, t in TEAM.items():
        for tok in t["tokens"]:
            if tok in f:
                return t["core"], t
    return "football fan", TEAM["Cleveland Browns"]


def garment_of(name: str):
    f = " " + _fold(name) + " "
    for g, d in GARMENT.items():
        for w in d["words"]:
            if f" {w} " in f or f.endswith(f" {w} ") or f" {w} " in f:
                return g, d
    return "Short Sleeve T-Shirt", GARMENT["Short Sleeve T-Shirt"]


def theme_of(name: str):
    f = _fold(name)
    for key in THEME_PRIORITY:
        d = THEME[key]
        for w in d["words"]:
            if w in f:
                return d["kw"]
    return ""


