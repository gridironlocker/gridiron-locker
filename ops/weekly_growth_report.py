#!/usr/bin/env python3
"""Weekly growth report assembler.

Reads the repo's verified data (Search Console export, indexing issues,
backlink snapshot, feed/catalogue health, SEO audit findings) and writes
WEEKLY-GROWTH-REPORT-<today>.md. Numbers that live behind logins this repo
cannot reach (GA4 engagement/purchases, Merchant Center status counts,
partner order exports) appear as NEEDS-INPUT blocks with the exact field
names - they are never guessed or filled with placeholders that look like
real data.

Run:  python3 ops/weekly_growth_report.py
Safe: reads data/ and site/, writes one markdown file at the repo root.
"""
import datetime
import json
import os
import re
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
G = "{http://base.google.com/ns/1.0}"


def read_json(*parts):
    with open(os.path.join(ROOT, *parts)) as fh:
        return json.load(fh)


def feed_health():
    root = ET.parse(os.path.join(ROOT, "site", "feeds", "google-merchant.xml"))
    items = root.getroot().findall("./channel/item")
    priced = [i for i in items if (i.find(G + "price").text or "").strip()]
    ids = {(i.find(G + "id").text or "") for i in items}
    stale = set()
    for fname, key in (("data/delisted.json", "slugs"),
                       ("data/fulfillment.json", "hold")):
        try:
            stale |= set(read_json(*fname.split("/"))[key])
        except Exception:
            pass
    leaked = sorted(ids & stale)
    return len(items), len(priced), leaked


def main():
    today = datetime.date.today().isoformat()
    gsc = read_json("data", "seo", "gsc_export.json")
    rows, queries = gsc.get("rows", []), gsc.get("queries", [])
    clicks = sum(r["clicks"] for r in rows)
    impressions = sum(r["impressions"] for r in rows)
    ctr = (clicks / impressions * 100) if impressions else 0.0
    n_items, n_priced, leaked = feed_health()
    cat = read_json("data", "catalogue-live.json")
    n_products = len(cat["products"])
    hold = len(read_json("data", "fulfillment.json").get("hold", []))
    delisted = len(read_json("data", "delisted.json").get("slugs", []))
    try:
        audit = read_json("data", "seo", "last_audit.json")
        findings = audit.get("findings", [])
    except Exception:
        findings = []
    weak = [f for f in findings if "weak_ctr" in (f.get("type") or "")]
    high = [f for f in findings if f.get("severity") == "high"]
    try:
        bl = read_json("data", "seo", "backlinks.json")
        bl_total = sum(r.get("backlinks", 0) for r in bl.get("rows", []))
        bl_date = bl.get("snapshot_date", "?")
    except Exception:
        bl_total, bl_date = 0, "?"

    L = []
    L.append(f"# Weekly growth report - {today}")
    L.append("")
    L.append("Generated by `ops/weekly_growth_report.py` from repo-held data.")
    L.append("Rows marked **NEEDS INPUT** come from logins this repo cannot")
    L.append("reach (GA4, Merchant Center, Viralstyle/Mayzing dashboards) -")
    L.append("fill them in from those dashboards; they are never estimated.")
    L.append("")
    L.append("## Organic search (Search Console export, "
             f"imported {gsc.get('updated', '?')[:10]}; export window not "
             "recorded in the file - note the range on the next export)")
    L.append("")
    L.append(f"- Clicks **{clicks}** - Impressions **{impressions}** - "
             f"CTR **{ctr:.2f}%**")
    L.append("- Top pages by impressions:")
    for r in sorted(rows, key=lambda x: -x["impressions"])[:6]:
        p = r["page"].replace("https://gridironlocker.store", "")
        L.append(f"  - `{p}` - {r['impressions']} impr / {r['clicks']} clk "
                 f"/ pos {r['position']:.1f}")
    L.append("- Top queries by impressions:")
    for q in sorted(queries, key=lambda x: -x["impressions"])[:6]:
        L.append(f"  - \"{q['query']}\" - {q['impressions']} impr / "
                 f"{q['clicks']} clk / pos {q['position']:.1f}")
    L.append("")
    L.append("## Indexing (Search Console issues export)")
    L.append("")
    try:
        idx = read_json("data", "seo", "gsc_indexing.json")
        for r in idx.get("issues", []):
            L.append(f"- {r.get('reason')}: {r.get('pages', '?')} pages - "
                     f"validation {r.get('validation') or 'n/a'}")
    except Exception:
        L.append("- (gsc_indexing.json unreadable)")
    L.append("")
    L.append("## Google Merchant Center - NEEDS INPUT")
    L.append("")
    L.append("| Metric | This week | Last week |")
    L.append("|---|---|---|")
    for m in ("Total products", "Approved", "Limited", "Not approved",
              "Under review", "Free-listing clicks", "Free-listing impressions"):
        L.append(f"| {m} | NEEDS INPUT | |")
    L.append("")
    L.append("## Funnel & revenue (GA4 + partner dashboards) - NEEDS INPUT")
    L.append("")
    L.append("| Metric | This week | Last week |")
    L.append("|---|---|---|")
    for m in ("Sessions (organic)", "Sessions (google/organic free listings)",
              "product_page_view", "shop_now_click",
              "viralstyle_checkout_click", "mayzing_checkout_click",
              "Add to cart (partner dashboard)", "Checkout starts (partner)",
              "Completed purchases (partner)", "Revenue (partner)",
              "Average order value (partner)", "Conversion rate"):
        L.append(f"| {m} | NEEDS INPUT | |")
    L.append("")
    L.append("## Store & feed health (verified now)")
    L.append("")
    L.append(f"- Catalogue: **{n_products}** live products")
    L.append(f"- Merchant feed: **{n_items}** items, **{n_priced}** with price, "
             f"stale-slug leaks: **{leaked if leaked else 'none'}**")
    L.append(f"- Retired catalogue: {delisted} delisted + {hold} on hold "
             "(never in feed)")
    L.append(f"- SEO audit findings: {len(findings)} total, high={len(high)}, "
             f"weak-CTR opportunities={len(weak)}")
    L.append(f"- Backlinks (snapshot {bl_date}): {bl_total} links across the "
             "exported URLs")
    L.append("")
    L.append("## Actions this week")
    L.append("")
    L.append("- (fill: what shipped, what the operator did)")
    L.append("")
    L.append("## Decisions / asks")
    L.append("")
    L.append("- (fill: approvals pending, inputs needed)")

    out = os.path.join(ROOT, f"WEEKLY-GROWTH-REPORT-{today}.md")
    with open(out, "w") as fh:
        fh.write("\n".join(L) + "\n")
    print("wrote", out)


if __name__ == "__main__":
    main()
